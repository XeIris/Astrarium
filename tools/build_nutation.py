#!/usr/bin/env python3
"""Build sim/observatory/nutation2000b.gd, the IAU 2000B nutation series, from ERFA.

    python3 tools/build_nutation.py path/to/nut00b.c

nut00b.c is ERFA's eraNut00b (github.com/liberfa/erfa, src/nut00b.c; BSD-3, © 2013–2023
NumFOCUS Foundation, derived from the IAU SOFA library). The 77 luni-solar terms
(McCarthy & Luzum 2003) are copied in its order with their units, 0.1 µas; the
fixed offsets stand in for the planetary terms.
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "sim" / "observatory" / "nutation2000b.gd"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1]).read_text()
    table = src[src.index("} x[] = {"):src.index("};", src.index("} x[] = {"))]
    num = r"\s*(-?\d+(?:\.\d*)?)\s*"
    rows = re.findall(r"\{" + ",".join([num] * 11) + r"\}", table)
    plan = {k: float(v) for k, v in re.findall(r"(DPPLAN|DEPLAN)\s*=\s*(-?[\d.]+)\s*\*\s*ERFA_DMAS2R", src)}
    if len(rows) != 77 or set(plan) != {"DPPLAN", "DEPLAN"}:
        sys.exit(f"build_nutation: {len(rows)} terms, offsets {plan}; nut00b.c's layout may have changed")
    lines = ",\n".join("\t[%s, %s]" % (", ".join(r[:5]), ", ".join(f if "." in f else f + ".0" for f in r[5:]))
                        for r in rows)
    OUT.write_text(f"""class_name Nutation2000B
extends RefCounted

# IAU 2000B nutation (McCarthy & Luzum 2003), generated by tools/build_nutation.py from
# ERFA's nut00b.c (BSD-3, © NumFOCUS Foundation; from IAU SOFA). Each term: the
# multiples of l, l′, F, D, Ω, then ψ sin, ψ t·sin, ψ cos and ε cos, ε t·cos, ε sin in
# 0.1 µas (t in Julian centuries TT). The fixed offsets (rad) replace the planetary terms.

const DPPLAN := {plan['DPPLAN']} * 1e-3 * PI / 648000.0
const DEPLAN := {plan['DEPLAN']} * 1e-3 * PI / 648000.0
const TERMS := [
{lines},
]
""")
    print(f"build_nutation: 77 terms -> {OUT}")


if __name__ == "__main__":
    main()
