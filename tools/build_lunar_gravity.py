#!/usr/bin/env python3
"""Write sim/flight/lunar_gravity.gd: the Moon's gravity field to degree 16 from JPL's
GRAIL solution GL0420A (Konopliv et al. 2013), as distributed by the PDS Geosciences
Node (GRAIL-L-LGRS-5-RDR-V1, shadr/jggrx_0420a_sha.tab).

Rows are sorted by degree, so the first ~64 KB of the file suffice:
  curl -r 0-65535 -o jggrx_0420a_sha_head.tab \\
    https://pds-geosciences.wustl.edu/grail/grail-l-lgrs-5-rdr-v1/grail_1001/shadr/jggrx_0420a_sha.tab
  python3 tools/build_lunar_gravity.py jggrx_0420a_sha_head.tab
"""
import pathlib
import sys

NMAX = 16
OUT = pathlib.Path(__file__).resolve().parent.parent / "sim/flight/lunar_gravity.gd"


def main(path):
    lines = pathlib.Path(path).read_text().splitlines()
    head = [f.strip() for f in lines[0].split(",")]
    r_km, gm_km3, deg_max, norm = float(head[0]), float(head[1]), int(head[3]), int(head[5])
    if norm != 1 or deg_max < NMAX:
        sys.exit(f"expected a fully normalized field to degree >= {NMAX}; header says {head}")
    C, S = {}, {}
    for line in lines[1:]:
        f = [x.strip() for x in line.split(",")]
        if len(f) < 4 or not f[0].isdigit():
            continue
        n, m = int(f[0]), int(f[1])
        if n > NMAX:
            break
        C[(n, m)] = float(f[2])
        S[(n, m)] = float(f[3])
    want = [(n, m) for n in range(NMAX + 1) for m in range(n + 1)]
    missing = [k for k in want if k not in C and k[0] >= 2]
    if missing:
        sys.exit(f"truncated before degree {NMAX}: missing {missing[:3]}")
    def row(table):
        vals = [table.get(k, 0.0) for k in want]
        return ",\n\t".join(", ".join(f"{v:.13e}" for v in vals[i:i + 6]) for i in range(0, len(vals), 6))
    OUT.write_text(f"""class_name LunarGravity
extends RefCounted

# The Moon's gravity field to degree {NMAX}, fully normalized, in the principal-axis frame:
# GL0420A (JPL, GRAIL primary mission; Konopliv et al. 2013, JGR Planets 118, 1415), from the PDS Geosciences Node,
# GRAIL-L-LGRS-5-RDR-V1 shadr/jggrx_0420a_sha.tab. Generated by
# tools/build_lunar_gravity.py; do not edit. Index n(n+1)/2 + m.

const R_REF := {r_km * 1000.0:.1f}           # m
const GM := {gm_km3 * 1e9:.10e}     # m³/s²
const NMAX := {NMAX}
const C := [
\t{row(C)},
]
const S := [
\t{row(S)},
]
""")
    print(f"wrote {OUT} (degree {NMAX}, {len(want)} terms, R {r_km} km)")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
