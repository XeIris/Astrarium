#!/usr/bin/env python3
"""Build sim/observatory/deltat.gd, measured ΔT = TT − UT1, from the USNO's tables.

    python3 tools/build_deltat.py path/to/historic_deltat.data path/to/deltat.data

Both files are from the USNO's IERS Rapid Service/Prediction Centre
(https://maia.usno.navy.mil/ser7/): historic_deltat.data, half-yearly from 1657 to
1984.5 with its standard error, and deltat.data, monthly from 1973 February. The
historic rows are used up to 1973.0, the monthly ones after; a monthly value is
given a 0.01 s error (it is UT1 from VLBI, good to milliseconds). Decimal years are
Julian years from J2000 (EarthFrame.year_of), so a monthly date is converted
through its Julian date.
"""
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "sim" / "observatory" / "deltat.gd"


def jd(y, m, d):
    if m <= 2:
        y, m = y - 1, m + 12
    a = y // 100
    return int(365.25 * (y + 4716)) + int(30.6001 * (m + 1)) + d + 2 - a + a // 4 - 1524.5


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    rows = []
    for line in Path(sys.argv[1]).read_text().splitlines():
        p = line.split()
        try:
            y, dt, err = float(p[0]), float(p[1]), float(p[2])
        except (ValueError, IndexError):
            continue
        if y <= 1973.0:
            rows.append((y, dt, err))
    for line in Path(sys.argv[2]).read_text().splitlines():
        p = line.split()
        if len(p) != 4:
            continue
        y = 2000.0 + (jd(int(p[0]), int(p[1]), int(p[2])) - 2451545.0) / 365.25
        if y > rows[-1][0]:
            rows.append((y, float(p[3]), 0.01))
    if len(rows) < 1000 or rows[0][0] > 1700.0 or rows[-1][0] < 2020.0:
        sys.exit(f"build_deltat: {len(rows)} rows from {rows[0][0]} to {rows[-1][0]}; the tables' layout may have changed")
    last = rows[-1][0]
    body = ",\n".join("\t[%.4f, %.4f, %.3f]" % r for r in rows)
    OUT.write_text(f"""class_name DeltaT
extends RefCounted

# Measured ΔT = TT − UT1 (s), generated by tools/build_deltat.py from the USNO's
# historic_deltat.data (to 1973.0) and deltat.data (monthly). Rows are [Julian
# decimal year, ΔT, 1σ].

const SOURCE := "USNO/IERS, to {last:.2f}"
const TABLE := [
{body},
]
""")
    print(f"build_deltat: {len(rows)} rows, {rows[0][0]:.1f} to {last:.3f} (ΔT {rows[-1][1]:.3f} s) -> {OUT}")


if __name__ == "__main__":
    main()
