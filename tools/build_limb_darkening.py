#!/usr/bin/env python3
"""Build sim/limbdark.gd: quadratic limb-darkening coefficients from Claret (2000).

    python3 -I tools/build_limb_darkening.py atlas_a.tsv atlas_b.tsv phoenix.tsv

Claret, A&A 363, 1081 (2000), VizieR J/A+A/363/1081, at log g 4.5, [M/H] 0 and a
microturbulence of 2 km/s, in the Johnson–Cousins B, V and R bands that stand in for
the renderer's 440, 550 and 650 nm primaries:
- `atlasco`, Coeff a and b: the quadratic law I(μ)/I(1) = 1 − a(1 − μ) − b(1 − μ)² from
  ATLAS models, 3500–50 000 K (asu-tsv, -out=Coeff,VT,logg,Teff,log[M/H],B,V,R).
- `phoenix` (table 38): the four-parameter law 1 − Σ a_k(1 − μ^(k/2)) from PHOENIX
  models, used below 3500 K and refitted here to the quadratic by least squares on
  101 points uniform in μ.
"""
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "sim" / "limbdark.gd"
BANDS = ("R", "V", "B")     # the renderer's R, G, B primaries


def rows(path):
    head, out = None, []
    for line in Path(path).read_text().splitlines():
        if not line.strip() or line.startswith("#") or line.startswith("-"):
            continue
        cells = [c.strip() for c in line.split("\t")]
        if head is None:
            head = cells
            continue
        try:
            float(cells[head.index("Teff")])
        except ValueError:
            continue
        out.append(dict(zip(head, cells)))
    return out


def quad_fit(law):
    """Least-squares (a, b) of 1 − a x − b x², x = 1 − μ, to the intensity law(μ)."""
    sxx = sx3 = sx4 = sxy = sx2y = 0.0
    for n in range(101):
        mu = n / 100.0
        x = 1.0 - mu
        y = 1.0 - law(mu)
        sxx += x * x; sx3 += x ** 3; sx4 += x ** 4; sxy += x * y; sx2y += x * x * y
    det = sxx * sx4 - sx3 * sx3
    return (sxy * sx4 - sx2y * sx3) / det, (sx2y * sxx - sxy * sx3) / det


def main(atlas_a, atlas_b, phoenix):
    table = {}
    a_rows = {float(r["Teff"]): r for r in rows(atlas_a)}
    b_rows = {float(r["Teff"]): r for r in rows(atlas_b)}
    for t in sorted(a_rows):
        table[t] = ([float(a_rows[t][k]) for k in BANDS], [float(b_rows[t][k]) for k in BANDS], "ATLAS")
    atlas_lo = min(table)
    ph = {}
    for r in rows(phoenix):
        ph.setdefault(float(r["Teff"]), {})[r["Coeff"].strip()] = r
    for t in sorted(ph):
        if t >= atlas_lo:
            continue
        ab = [quad_fit(lambda mu, c=c: 1.0 - sum(float(ph[t]["a%d" % k][c]) * (1.0 - mu ** (k / 2.0)) for k in range(1, 5)))
              for c in BANDS]
        table[t] = ([x[0] for x in ab], [x[1] for x in ab], "PHOENIX, refitted")
    if len(table) < 60:
        sys.exit("only %d temperatures parsed" % len(table))
    lines = []
    for t in sorted(table):
        a, b, src = table[t]
        lines.append("\t[%.0f, %.4f, %.4f, %.4f, %.4f, %.4f, %.4f]," % (t, *a, *b))
    OUT.write_text('''class_name LimbDark
extends RefCounted

# Quadratic limb darkening, I(μ)/I(1) = 1 − a(1 − μ) − b(1 − μ)², from Claret (2000), A&A
# 363, 1081 (VizieR J/A+A/363/1081): log g 4.5, [M/H] 0, ξ 2 km/s, Cousins R, Johnson V
# and B for the R, G, B primaries. ATLAS quadratic coefficients from 3500 K; below,
# PHOENIX four-parameter laws refitted to the quadratic. Generated by
# tools/build_limb_darkening.py; do not edit.

## [Teff K, a_R, a_G, a_B, b_R, b_G, b_B], ascending Teff.
const TABLE := [
%s
]
''' % "\n".join(lines))
    print("%d temperatures, %.0f–%.0f K -> %s" % (len(table), min(table), max(table), OUT))


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
